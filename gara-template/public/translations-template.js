// Lingua corrente
let currentLang = localStorage.getItem('lang') || 'it';

// Funzione per ottenere traduzione
function t(key) {
  let text = T[currentLang]?.[key] || T['it'][key] || key;
  
  // Sostituisci placeholder con valori dal config
  if (window.GARA_CONFIG) {
    const cfg = window.GARA_CONFIG;
    text = text.replace('{{EVENT_NAME}}', cfg.event.fullName || '');
    text = text.replace('{{EVENT_TAGLINE}}', cfg.event.tagline || '');
    text = text.replace('{{EVENT_TAGLINE_EN}}', cfg.event.tagline_en || cfg.event.tagline || '');
    text = text.replace('{{EVENT_LOCATION}}', `${cfg.event.location.city}, ${cfg.event.location.country}` || '');
    
    // Formatta date
    if (cfg.event.dates) {
      const start = new Date(cfg.event.dates.start);
      const end = new Date(cfg.event.dates.end);
      const dateStr = `${start.getDate()}-${end.getDate()}/${start.getMonth()+1}/${start.getFullYear()}`;
      text = text.replace('{{EVENT_DATES}}', dateStr);
    }
  }
  
  return text;
}

// Cambia lingua
function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('lang', lang);
  applyTranslations();
}

// Applica traduzioni alla pagina
function applyTranslations() {
  document.querySelectorAll('[data-t]').forEach(el => {
    const key = el.getAttribute('data-t');
    const translation = t(key);
    if (el.tagName === 'INPUT' && el.type !== 'submit') {
      el.placeholder = translation;
    } else {
      el.textContent = translation;
    }
  });
  
  // Aggiorna attributi data-t-*
  document.querySelectorAll('[data-t-title]').forEach(el => {
    el.title = t(el.getAttribute('data-t-title'));
  });
  document.querySelectorAll('[data-t-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-t-placeholder'));
  });
  
  // Aggiorna lang-switcher
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });
}

// Inizializza traduzioni quando il DOM è pronto
document.addEventListener('DOMContentLoaded', () => {
  // Aspetta che il config sia caricato
  document.addEventListener('configLoaded', () => {
    applyTranslations();
  });
  
  // Se il config è già caricato
  if (window.GARA_CONFIG) {
    applyTranslations();
  }
});
